/**
 * Tailwind v4 cannot see utility class names that live only in compiled CMS
 * blocks (stored in the DB as JSON). Recreate a safelist from those blocks so
 * arbitrary-value classes such as `text-[var(--color-off-white)]` are emitted
 * into the production stylesheet. Run after compile-blocks.mts:
 *
 *   TURSO_DATABASE_URL=file:local.db node scripts/build-block-safelist.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { createClient } from '@libsql/client'

const client = createClient({
  url: process.env.TURSO_DATABASE_URL || 'file:local.db',
  authToken: process.env.TURSO_AUTH_TOKEN,
})
const classes = new Set()
try {
  const rows = await client.execute('SELECT blocks FROM pages')
  for (const row of rows.rows) {
    let blocks
    try { blocks = JSON.parse(String(row.blocks ?? '[]')) } catch { continue }
    const walk = (b) => {
      if (!b || typeof b !== 'object') return
      if (typeof b.cls === 'string') {
        for (const token of b.cls.split(/\s+/)) {
          if (token && /\[[^\]]+\]/.test(token)) classes.add(token)
        }
      }
      for (const child of b.children ?? []) walk(child)
    }
    if (Array.isArray(blocks)) blocks.forEach(walk)
  }
} finally {
  await client.close()
}

const sorted = [...classes].sort()
// Emit in chunks to keep each @source inline() directive manageable.
const chunks = []
for (let i = 0; i < sorted.length; i += 120) chunks.push(sorted.slice(i, i + 120).join(' '))
const out = [
  '/* GENERATED by scripts/build-block-safelist.mjs — do not edit by hand. */',
  '/* Arbitrary-value utilities referenced only from CMS compiled blocks. */',
  ...chunks.map((c) => `@source inline("${c.replace(/"/g, '\\"')}");`),
  '',
].join('\n')
const target = path.join(process.cwd(), 'src', 'styles', 'block-safelist.css')
fs.writeFileSync(target, out)
console.log(`wrote ${target} (${sorted.length} classes, ${chunks.length} directives)`)
